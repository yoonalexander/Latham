import { test, expect, _electron, type ElectronApplication } from "@playwright/test";
import { mkdtempSync, readFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { ServiceStore } from "../../services/managed-ai/store";
import { managedService } from "../../services/managed-ai/server";

test("managed account onboarding, DPAPI restart, explicit route, speech, Stop, usage, cancellation and deletion", async () => {
  test.setTimeout(90000);
  const directory = mkdtempSync(resolve(".test-artifacts/phase8-account-")), data = join(directory, "desktop");
  const store = new ServiceStore(join(directory, "service.sqlite")), invitation = store.invite(20);
  let held: ((response: Response) => void) | null = null, delay = false;
  const provider = async (_url: string | URL | Request, init?: RequestInit): Promise<Response> => {
    expect((init?.headers as Record<string, string>)["x-goog-api-key"]).toBe("ISOLATED_SERVER_TEST_KEY");
    const response = Response.json({ candidates: [{ finishReason: "STOP", content: { parts: [{ text: String(init?.body).includes("audio/wav") ? "piano music" : '{"candidateId":"search"}' }] } }] });
    if (delay) return new Promise<Response>(resolve => { held = resolve; });
    return response;
  };
  const service = managedService({ store, key: "ISOLATED_SERVER_TEST_KEY", dailyRequests: 100, totalRequests: 1000, request: provider });
  await new Promise<void>(resolve => service.server.listen(0, "127.0.0.1", resolve));
  const address = service.server.address(); if (!address || typeof address === "string") throw new Error("missing_address");
  const origin = `http://127.0.0.1:${address.port}`;
  const env = Object.fromEntries(Object.entries(process.env).filter((pair): pair is [string, string] => pair[1] !== undefined && pair[0] !== "ELECTRON_RUN_AS_NODE"));
  let app: ElectronApplication | undefined;
  const launch = async () => {
    app = await _electron.launch({ args: [resolve("dist/main.cjs"), "--latham-test"], env: { ...env, LATHAM_TEST_DATA_DIR: data } });
    await expect.poll(() => app!.context().pages().some(page => page.url() === "latham://app/index.html")).toBe(true);
    const page = app.context().pages().find(page => page.url() === "latham://app/index.html")!;
    await page.getByRole("button", { name: "Advanced settings", exact: true }).click();
    return page;
  };
  try {
    let page = await launch(), panel = page.getByRole("region", { name: "Managed AI account", exact: true });
    expect((await page.evaluate(() => window.setup.state())).settings.mode).toBe("local");
    await panel.getByLabel("Managed service address", { exact: true }).fill(origin);
    await panel.getByLabel("One-time invitation", { exact: true }).fill(invitation.invite);
    await expect(panel.getByRole("button", { name: "Sign in with invitation", exact: true })).toBeDisabled();
    await panel.getByRole("checkbox").check();
    await panel.getByRole("button", { name: "Sign in with invitation", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).managed.signedIn)).toBe(true);
    expect((await page.evaluate(() => window.setup.state())).settings.mode).toBe("local");
    expect(JSON.stringify(await page.evaluate(() => window.setup.state()))).not.toContain(invitation.invite);
    expect(readFileSync(join(data, "managed-session.bin")).toString()).not.toContain(origin);
    await page.getByRole("radio", { name: "Latham-managed AI" }).check();
    await page.getByRole("button", { name: "Save AI setup", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).settings.mode)).toBe("managed");
    await page.getByRole("button", { name: "Test saved decision setup", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).notice)).toContain("Decision fixture passed");
    await page.evaluate(async () => { const id = await window.setup.beginTurn(); await window.setup.finishTurn(id, new Int16Array(1600).fill(1000).buffer); });
    await expect(page.getByLabel("Final transcript", { exact: true })).toHaveValue("piano music");
    expect((await page.evaluate(() => window.setup.state())).canInsertTranscript).toBe(false);
    expect(existsSync(join(data, "provider-key.bin"))).toBe(false);
    await panel.getByRole("button", { name: "Refresh usage", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).managed.usage?.used)).toBe(2);
    await panel.screenshot({ path: ".test-artifacts/phase8-managed-account.png" });
    await app!.close(); app = undefined;
    page = await launch(); panel = page.getByRole("region", { name: "Managed AI account", exact: true });
    const restarted = await page.evaluate(() => window.setup.state());
    expect(restarted.managed.signedIn).toBe(true); expect(restarted.settings.mode).toBe("managed"); expect(restarted.voice).toBe("idle"); expect(restarted.transcript).toBe(""); expect(restarted.handsfree.phase).toBe("off");
    delay = true;
    const pending = page.evaluate(async () => { const id = await window.setup.beginTurn(); await window.setup.finishTurn(id, new Int16Array(1600).fill(1000).buffer); });
    await expect.poll(() => service.metrics().active).toBe(1);
    await page.evaluate(() => window.latham.stop());
    const release = held as ((response: Response) => void) | null;
    release?.(Response.json({ candidates: [{ finishReason: "STOP", content: { parts: [{ text: "late words" }] } }] }));
    await pending; delay = false;
    expect((await page.evaluate(() => window.setup.state())).transcript).toBe("");
    await panel.getByLabel("Type cancel to stop service, or delete to erase this account", { exact: true }).fill("cancel");
    await panel.getByRole("button", { name: "Cancel managed service", exact: true }).click();
    await expect(panel.getByTestId("managed-status")).toContainText("Service cancelled");
    const admitted = service.metrics().admitted;
    await page.getByRole("button", { name: "Test saved decision setup", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).error)).not.toBe("");
    expect(service.metrics().admitted).toBe(admitted);
    await panel.getByLabel("Type cancel to stop service, or delete to erase this account", { exact: true }).fill("delete");
    await panel.getByRole("button", { name: "Delete managed account", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).managed.signedIn)).toBe(false);
    expect(existsSync(join(data, "managed-session.bin"))).toBe(false);
    expect((await page.evaluate(() => window.setup.state())).settings.mode).toBe("managed");
    await page.getByRole("radio", { name: "Use local AI", exact: true }).check();
    await page.getByRole("button", { name: "Save AI setup", exact: true }).click();
    await expect.poll(() => page.evaluate(async () => (await window.setup.state()).settings.mode)).toBe("local");
    expect(readFileSync(join(directory, "service.sqlite")).toString()).not.toContain(invitation.accountId);
  } finally { if (app) await app.close(); await service.stop(); store.close(); }
});
